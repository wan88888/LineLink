// Uses an installed Playwright package; override its module path for a shared tool runtime.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const url = process.env.TEST_URL || 'http://127.0.0.1:5726';
(async () => {
  const browser = await chromium.launch({ headless:true });
  try {
    const page = await browser.newPage({ viewport: {width:390,height:844}, reducedMotion:'reduce' });
    const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.goto(url);
    await page.getByRole('button',{name:'继续第 1 关',exact:true}).waitFor();
    await page.getByRole('button',{name:'选择关卡',exact:true}).click();
    assert.equal(await page.locator('.level-card').count(),48);
    await page.getByRole('button',{name:'返回主页',exact:true}).click();
    await page.getByRole('button',{name:'设置',exact:true}).click();
    await page.locator('#sound-toggle').uncheck();
    await page.getByRole('button',{name:'完成',exact:true}).click();
    await page.reload();
    assert.equal(await page.evaluate(()=>localStorage.getItem('linelink-sound')),'off');
    await page.getByRole('button',{name:'继续第 1 关',exact:true}).click();
    await page.getByRole('button',{name:'开始画吧',exact:true}).click();
    await page.locator('#loading').waitFor({state:'hidden'});
    assert.equal(await page.locator('canvas').count(),1);
    const level = await page.evaluate(async()=> (await import('/src/game/simulation/levels.ts')).createLevelCatalog()[0]);
    const points = async () => {
      const rect=await page.locator('canvas').boundingBox();
      const cell=Math.min(rect.width*.86/(level.cols-1),rect.height*.78/(level.rows-1));
      return level.nodes.map(p=>({x:rect.x+(rect.width-cell*(level.cols-1))/2+p.col*cell,y:rect.y+(rect.height-cell*(level.rows-1))/2+p.row*cell}));
    };
    let nodes=await points();
    await page.mouse.move(nodes[0].x,nodes[0].y);await page.mouse.down();
    await page.mouse.move(nodes[1].x,nodes[1].y,{steps:12});await page.mouse.up();
    assert.match(await page.locator('#game-status').innerText(),/1 \/ 3/);
    const rect=await page.locator('canvas').boundingBox();
    await page.mouse.click(rect.x+rect.width/2,rect.y+rect.height/2);
    assert.match(await page.locator('#game-status').innerText(),/1 \/ 3/);
    await page.setViewportSize({width:320,height:568});
    await page.waitForFunction(()=>document.querySelector('canvas').width===document.querySelector('#game-canvas-host').clientWidth);
    assert.match(await page.locator('#game-status').innerText(),/1 \/ 3/);
    nodes=await points();
    await page.mouse.move(nodes[1].x,nodes[1].y);await page.mouse.down();
    await page.mouse.move(nodes[2].x,nodes[2].y,{steps:12});
    await page.mouse.move(nodes[0].x,nodes[0].y,{steps:12});await page.mouse.up();
    await page.locator('#result-dialog[open]').waitFor();
    assert.match(await page.locator('#result-stars').innerText(),/★★★/);
    await page.getByRole('button',{name:'继续挑战',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#level-title').textContent.includes('第 2 关') && document.querySelector('#loading').classList.contains('hidden'));
    assert.equal(await page.locator('canvas').count(),1);
    await page.getByRole('button',{name:'返回关卡页',exact:true}).click();
    await page.locator('.level-card').nth(1).click();
    await page.locator('#loading').waitFor({state:'hidden'});
    assert.equal(await page.locator('canvas').count(),1);
    await page.screenshot({path:'/tmp/linelink-mobile.png'});
    await page.setViewportSize({width:844,height:390});
    await page.waitForFunction(()=>document.querySelector('canvas').width===document.querySelector('#game-canvas-host').clientWidth);
    const controls=await page.locator('#reset-btn').boundingBox();
    assert(controls.y+controls.height<=390,'landscape controls clipped');
    await page.screenshot({path:'/tmp/linelink-landscape.png'});
    await page.reload();
    await page.getByRole('button',{name:'继续第 2 关',exact:true}).waitFor();
    assert.equal(await page.locator('#star-value').innerText(),'3');
    assert.deepEqual(errors,[]);
    // A fresh page exercises import failure, recovery, and leaving during pending initialization.
    const retry=await browser.newPage({viewport:{width:390,height:844}});
    let fail=true;
    await retry.route('**/src/phaser/scenes/PuzzleScene.ts*',route=>fail?route.abort():route.continue());
    await retry.goto(url);
    await retry.getByRole('button',{name:'继续第 1 关',exact:true}).click();
    await retry.getByRole('button',{name:'重试加载',exact:true}).waitFor();
    fail=false;
    await retry.getByRole('button',{name:'重试加载',exact:true}).click();
    await retry.getByRole('button',{name:'开始画吧',exact:true}).click();
    assert.equal(await retry.locator('canvas').count(),1);
    await retry.close();
    const concurrent=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
    let release;
    const gate=new Promise(resolve=>{release=resolve});
    await concurrent.route('**/src/phaser/scenes/PuzzleScene.ts*',async route=>{await gate;await route.continue()});
    await concurrent.goto(url);
    await concurrent.locator('#play-btn').click();
    await concurrent.locator('#game-back-btn').click();
    await concurrent.locator('.level-card').first().click();
    release();
    await concurrent.getByRole('button',{name:'开始画吧',exact:true}).click();
    assert.equal(await concurrent.locator('canvas').count(),1,'concurrent initialization created duplicate canvases');
    await concurrent.close();

    const last=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});
    await last.addInitScript(()=>{
      const records={};for(let id=1;id<48;id++) records[id]={solved:true,bestAttempts:1,stars:3};
      localStorage.setItem('linelink-progress-v3',JSON.stringify({version:3,unlockedLevel:48,records}));
      localStorage.setItem('linelink-help-seen','yes');
    });
    await last.goto(url);
    await last.locator('#play-btn').click();
    await last.locator('#loading').waitFor({state:'hidden'});
    const finalLevel=await last.evaluate(async()=> (await import('/src/game/simulation/levels.ts')).createLevelCatalog()[47]);
    const adj=finalLevel.nodes.map(n=>finalLevel.edges.flatMap(([a,b],i)=>a.row===n.row&&a.col===n.col?[{next:finalLevel.nodes.findIndex(x=>x.row===b.row&&x.col===b.col),edge:i}]:b.row===n.row&&b.col===n.col?[{next:finalLevel.nodes.findIndex(x=>x.row===a.row&&x.col===a.col),edge:i}]:[]));
    const stack=[Math.max(0,adj.findIndex(a=>a.length%2))],trail=[],used=new Set();
    while(stack.length){const n=stack.at(-1),step=adj[n].find(x=>!used.has(x.edge));if(step){used.add(step.edge);stack.push(step.next)}else trail.push(stack.pop())}
    const lastRect=await last.locator('canvas').boundingBox();
    const cell=Math.min(lastRect.width*.86/4,lastRect.height*.78/4);
    const positions=trail.reverse().map(i=>({x:lastRect.x+(lastRect.width-4*cell)/2+finalLevel.nodes[i].col*cell,y:lastRect.y+(lastRect.height-4*cell)/2+finalLevel.nodes[i].row*cell}));
    await last.mouse.move(positions[0].x,positions[0].y);await last.mouse.down();
    for(const p of positions.slice(1)) await last.mouse.move(p.x,p.y,{steps:8});
    await last.mouse.up();
    await last.locator('#result-dialog[open]').waitFor();
    assert.equal(await last.locator('#result-title').innerText(),'48 关全部完成！');
    await last.screenshot({path:'/tmp/linelink-complete.png'});
    await last.locator('#result-next').click();
    await last.locator('#level-back-btn').click();
    assert.match(await last.locator('#play-btn').innerText(),/全部通关/);
    await last.close();
    console.log('PASS: concurrent startup and final-level completion; home, selection, mute persistence, initial load, blank tap, resize, drawing, result, next, re-entry, save restore, landscape, failed import retry');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1});
